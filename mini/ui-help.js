/** Open the help modal for a page (no-op if the page has no entry). */
function showHelp(page) {
  const info = HELP[page]; if (!info) return;
  const body = h('div', { class: 'help-body' });
  const lead = h('p', { class: 'help-lead' }); lead.innerHTML = info.lead; body.append(lead);
  const ul = h('ul', { class: 'help-tips' });
  for (const t of info.tips) { const li = document.createElement('li'); li.innerHTML = t; ul.append(li); }
  body.append(ul);
  modal(`${TITLES[page] || ''} — как пользоваться`, body, [
    { label: 'Полный гайд', fn: () => go('guide') },
    { label: 'Понятно', cls: 'primary' },
  ]);
}

/** Reflect the current page on the header "?" button (hidden when no help exists). */
function syncHelpBtn(page) {
  const b = $('helpBtn'); if (!b) return;
  b.hidden = !HELP[page];
  b.title = HELP[page] ? `Справка: ${TITLES[page] || ''}` : '';
}
